import { ResourcePage } from '@/components/data/ResourcePage';
import type { Column } from '@/components/data/DataTable';
import { StatusBadge } from '@/components/ui/Badge';
import type { FieldSchema } from '@/components/form/types';
import { reportService } from '@/services/soc';
import type { SocReport } from '@/types/models';
import { formatDateTime } from '@/utils/format';

const TYPES = ['Weekly SOC Summary', 'Incident Postmortem', 'Vulnerability Report', 'Compliance Report', 'Executive Briefing'];
const STATUSES = ['draft', 'ready', 'sent'];

const columns: Column<SocReport>[] = [
  { key: 'title', header: 'Title', sortable: true },
  { key: 'report_type', header: 'Type' },
  { key: 'period', header: 'Period' },
  { key: 'generated_by', header: 'Generated by' },
  { key: 'status', header: 'Status', sortable: true, render: (r) => <StatusBadge value={r.status} /> },
  { key: 'created_at', header: 'Created', sortable: true, render: (r) => formatDateTime(r.created_at) },
];

const schema: FieldSchema[] = [
  { name: 'title', label: 'Title', type: 'text', required: true, maxLength: 200 },
  { name: 'report_type', label: 'Type', type: 'select', required: true, options: TYPES.map((t) => ({ value: t, label: t })) },
  { name: 'period', label: 'Period', type: 'text', required: true, defaultValue: 'Last 7 days', colSpan: 1 },
  { name: 'status', label: 'Status', type: 'select', required: true, options: STATUSES.map((s) => ({ value: s, label: s })), defaultValue: 'draft', colSpan: 1 },
];

export default function ReportsPage() {
  return (
    <ResourcePage<SocReport>
      title="Reports"
      description="Generated SOC and compliance reports."
      entityName="report"
      service={reportService}
      columns={columns}
      filters={[{ key: 'status', label: 'Status', options: STATUSES.map((s) => ({ value: s, label: s })) }]}
      formSchema={schema}
      allowDelete
      searchPlaceholder="Search by title, type or author"
      defaultSort={{ key: 'created_at', order: 'desc' }}
      rowLabel={(r) => r.title}
      toPayload={(v) => ({ ...v, generated_by: 'You' }) as unknown as Partial<SocReport>}
    />
  );
}
